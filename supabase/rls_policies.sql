-- Aucun compte Supabase Auth ne donne un accès administrateur.
-- Les écritures passent par les actions serveur et service_role.
begin;
grant usage on schema public to anon, authenticated, service_role;
revoke all on public.clients from anon, authenticated;
grant all on public.clients to service_role;
revoke all on public.properties from anon, authenticated;
grant all on public.properties to service_role;
revoke all on public.property_images from anon, authenticated;
grant all on public.property_images to service_role;
revoke all on public.amenities from anon, authenticated;
grant all on public.amenities to service_role;
revoke all on public.viewing_requests from anon, authenticated;
grant all on public.viewing_requests to service_role;
revoke all on public.reservations from anon, authenticated;
grant all on public.reservations to service_role;
revoke all on public.request_submissions from anon, authenticated;
grant all on public.request_submissions to service_role;
revoke all on public.guarantee_payments from anon, authenticated;
grant all on public.guarantee_payments to service_role;
revoke all on public.refund_requests from anon, authenticated;
grant all on public.refund_requests to service_role;
revoke all on public.bank_settings from anon, authenticated;
grant all on public.bank_settings to service_role;
revoke all on public.contact_messages from anon, authenticated;
grant all on public.contact_messages to service_role;
revoke all on public.admin_logs from anon, authenticated;
grant all on public.admin_logs to service_role;
revoke all on public.status_history from anon, authenticated;
grant all on public.status_history to service_role;
revoke all on public.favorites from anon, authenticated;
grant all on public.favorites to service_role;
revoke all on public.site_settings from anon, authenticated;
grant all on public.site_settings to service_role;
revoke all on public.property_amenities from anon, authenticated;
grant all on public.property_amenities to service_role;
grant select on public.properties to anon, authenticated;
grant select on public.property_images to anon, authenticated;
grant select on public.amenities to anon, authenticated;
grant select on public.property_amenities to anon, authenticated;
grant select on public.site_settings to anon, authenticated;
create policy properties_public_read on public.properties for select to anon, authenticated using (is_published);
create policy property_images_public_read on public.property_images for select to anon, authenticated using (exists (select 1 from public.properties p where p.id = property_id and p.is_published));
create policy property_amenities_public_read on public.property_amenities for select to anon, authenticated using (exists (select 1 from public.properties p where p.id = property_id and p.is_published));
create policy amenities_public_read on public.amenities for select to anon, authenticated using (true);
create policy site_settings_public_read on public.site_settings for select to anon, authenticated using (id = 1);
commit;
